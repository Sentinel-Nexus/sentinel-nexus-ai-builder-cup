"""Injected review cases: evaluation alerts the service knows about besides the detector's.

`data/injected_alerts.json` is generated by `python -m scripts.injected_cases` from live detector
output (see evals/agents/cases.py). The service loads it as extra alerts so the four injected cases
can be stored, listed in the queue and shown in the lanes. They are always labelled as injected.
"""

from __future__ import annotations

import json

from services.app.config import REPO

PATH = REPO / "data" / "injected_alerts.json"


def load_injected() -> list[dict]:
    if not PATH.exists():
        return []
    return json.loads(PATH.read_text(encoding="utf-8"))
