"""Render docs/benchmark.md and docs/img/benchmark.png from eval.detector_results.

    python scripts/benchmark.py --iteration 1          # reads BigQuery (one small query)

Local files only; nothing in the cloud changes.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
METHODS = ("baseline_flat_rule", "detector_v1")
LABELS = {"baseline_flat_rule": "Flat rule (funding shared by 5+)", "detector_v1": "Detector v1"}
SCENARIOS = ("wash_trading", "coordinated_accumulation", "mule_funding")
LIGHT = {"bg": "#fcfcfb", "ink": "#0b0b0b", "muted": "#52514e", "grid": "#f0efec"}
# categorical slots 2 (orange) and 1 (blue) of the reference palette
COLORS = {"baseline_flat_rule": "#eb6834", "detector_v1": "#2a78d6"}


def fetch(project: str, iteration: int) -> list[dict]:
    from google.cloud import bigquery

    client = bigquery.Client(project=project, location="US")
    sql = f"""
      SELECT * FROM `{project}.eval.detector_results`
      WHERE iteration = {int(iteration)} ORDER BY split, seed, method, group_kind, group_name
    """
    return [dict(r.items()) for r in client.query(sql).result()]


def pick(rows, split, method, kind, name, seed=None):
    key = (split, method, kind, name)
    for r in rows:
        same = (r["split"], r["method"], r["group_kind"], r["group_name"]) == key
        if same and (seed is None or r["seed"] == seed):
            return r
    raise KeyError((*key, seed))


def pct(x) -> str:
    return "n/a" if x is None else f"{100 * x:.0f}%"


def chart(rows, out: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    groups = [("all_scenarios", "overall"), *[(s, "scenario") for s in SCENARIOS]]
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.2), facecolor=LIGHT["bg"], sharey=True)
    for ax, metric in zip(axes, ("precision", "recall"), strict=True):
        ax.set_facecolor(LIGHT["bg"])
        width = 0.36
        for i, method in enumerate(METHODS):
            xs, vals = [], []
            for j, (name, kind) in enumerate(groups):
                v = pick(rows, "evaluation", method, kind, name)[metric]
                xs.append(j + (i - 0.5) * (width + 0.04))
                vals.append(v or 0.0)
            bars = ax.bar(xs, vals, width, color=COLORS[method], label=LABELS[method])
            for bar, v in zip(bars, vals, strict=True):
                ax.text(
                    bar.get_x() + bar.get_width() / 2,
                    v + 0.02,
                    f"{100 * v:.0f}%",
                    ha="center",
                    va="bottom",
                    fontsize=8,
                    color=LIGHT["ink"],
                )
        ax.set_xticks(range(len(groups)))
        ax.set_xticklabels(
            [n.replace("_", "\n") if k == "scenario" else "overall" for n, k in groups],
            fontsize=8,
            color=LIGHT["muted"],
        )
        ax.set_ylim(0, 1.12)
        ax.set_yticks([0, 0.25, 0.5, 0.75, 1.0])
        ax.set_yticklabels(["0", "25%", "50%", "75%", "100%"], color=LIGHT["muted"], fontsize=8)
        ax.set_title(metric.capitalize(), loc="left", fontsize=11, color=LIGHT["ink"])
        ax.grid(axis="y", color=LIGHT["grid"], linewidth=0.8)
        ax.set_axisbelow(True)
        for side in ("top", "right", "left"):
            ax.spines[side].set_visible(False)
        ax.spines["bottom"].set_color(LIGHT["grid"])
        ax.tick_params(length=0)
    handles, names = axes[0].get_legend_handles_labels()
    fig.legend(
        handles,
        names,
        frameon=False,
        fontsize=9,
        loc="lower center",
        ncol=2,
        labelcolor=LIGHT["ink"],
    )
    fig.suptitle(
        "Seed 42 (held out): flat funding rule vs detector",
        x=0.01,
        ha="left",
        fontsize=12,
        color=LIGHT["ink"],
    )
    fig.tight_layout(rect=(0, 0.07, 1, 0.95))
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, dpi=160, facecolor=LIGHT["bg"])


def markdown(rows, frozen: dict, iteration: int) -> str:
    ev = "evaluation"
    lines = [
        "# Benchmark: flat rule vs detector v1",
        "",
        f"Generated by `scripts/benchmark.py` from `eval.detector_results` (iteration {iteration}).",  # noqa: E501
        "",
        "Data: seed 42, 2,039 accounts, 39 attackers (8 wash, 6 coordination, 25 mule), 23 decoy",
        "accounts in three innocent groups, 40% of attackers without a shared funding source",
        "(ADR 0002). The decoy table and ground truth are read only by the evaluation step.",
        "",
        "Baseline: flag every account whose funding source is shared by 5 or more accounts.",
        "",
        f"Detector: explainable linear score over nine scenario-agnostic features, flag at "
        f"score >= **{frozen['threshold']}**. The threshold was chosen on validation seeds "
        f"{frozen['validation_seeds']} (mean F1 {frozen['mean_f1']}) and frozen before seed 42 was scored.",  # noqa: E501
        "",
        "## Seed 42 (held-out evaluation)",
        "",
        "| Group | Method | Flagged | True pos | False pos | Precision | Recall | F1 |",
        "|---|---|---:|---:|---:|---:|---:|---:|",
    ]
    for kind, name in [("overall", "all_scenarios"), *[("scenario", s) for s in SCENARIOS]]:
        for m in METHODS:
            r = pick(rows, ev, m, kind, name)
            lines.append(
                f"| {name} | {LABELS[m]} | {r['flagged']} | {r['true_pos']} | {r['false_pos']} | "
                f"{pct(r['precision'])} | {pct(r['recall'])} | {pct(r['f1'])} |"
            )
    lines += [
        "",
        "Per-scenario precision is one-vs-rest: that scenario's true positives over those plus",
        "every flagged account that is not an attacker in any scenario.",
        "",
        "## Innocent groups (false positives)",
        "",
        "| Group | Accounts | Flat rule flagged | Detector flagged |",
        "|---|---:|---:|---:|",
    ]
    groups = sorted({r["group_name"] for r in rows if r["group_kind"] in ("decoy", "background")})
    for g in groups:
        kind = "background" if g == "normal_accounts" else "decoy"
        b, d = (pick(rows, ev, m, kind, g) for m in METHODS)
        lines.append(f"| {g} | {b['n_members']} | {b['flagged']} | {d['flagged']} |")
    lines += [
        "",
        "## Validation seeds (threshold selection)",
        "",
        "| Seed | Method | Precision | Recall | F1 |",
        "|---|---|---:|---:|---:|",
    ]
    for seed in frozen["validation_seeds"]:
        for m in METHODS:
            r = pick(rows, "validation", m, "overall", "all_scenarios", seed)
            lines.append(
                f"| {seed} | {LABELS[m]} | {pct(r['precision'])} | {pct(r['recall'])} | {pct(r['f1'])} |"  # noqa: E501
            )
    lines += [
        "",
        "![baseline vs detector per scenario](img/benchmark.png)",
        "",
        "## Caveats",
        "",
        "- The data is synthetic and the scenarios, decoys and detector come from the same",
        "  project. Perfect validation scores show this set is separable, not that the detector",
        "  generalises to real markets.",
        "- The margin is thin. On seed 42 one evaded coordination account scored 42.99 against",
        "  the 43.0 threshold and was missed. On validation seed 23 a busy-but-honest decoy",
        "  scored 42.2 while the weakest attacker scored 43.0.",
        "- Weights were set a priori and never fitted; only the threshold came from data, and only",
        "  from the validation seeds. Seed 42 was scored once per iteration, not used to tune.",
        "- `scenario_hint` is not measured here. In the seed 42 alerts the wash ring is hinted as",
        "  `mule_funding` because its fresh-account features outweigh matched-fill reciprocity.",
        "- The flat rule scores the same on every seed because the decoys and evasions are",
        "  generated identically; only the background trades differ.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--project", default=os.environ.get("PROJECT_ID"))
    ap.add_argument("--iteration", type=int, required=True)
    args = ap.parse_args()
    rows = fetch(args.project, args.iteration)
    frozen = json.loads((ROOT / "services/detector/threshold.json").read_text(encoding="utf-8"))
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs/benchmark.md").write_text(
        markdown(rows, frozen, args.iteration), encoding="utf-8", newline="\n"
    )
    chart(rows, ROOT / "docs/img/benchmark.png")
    print("wrote docs/benchmark.md and docs/img/benchmark.png")


if __name__ == "__main__":
    main()
